FILLER_DIR = os.path.expanduser("~/fillers")
BAIL_DIR = os.path.expanduser("~/fillers_bail")
BAIL_FILES = ["please_be_specific.wav", "not_connected.wav", "enroll_prompt.wav", "enroll_done.wav"]
STAMP = time.strftime("%Y%m%d")

client = _sync_client()
print(f"engine: {TTS_MODEL_DEFAULT} voice={TTS_VOICE_DEFAULT} instructions={'yes' if voice_io.TTS_INSTRUCTIONS_DEFAULT else 'NO'}")


def transcribe(path):
    with open(path, "rb") as f:
        return client.audio.transcriptions.create(model="whisper-1", file=f, language="en").text.strip()


def synth_wav(text, wav_path, rate=None):
    kw = tts_create_kwargs(TTS_MODEL_DEFAULT, TTS_VOICE_DEFAULT, TTS_SPEED_DEFAULT, text)
    mp3 = wav_path + ".mp3"
    with open(mp3, "wb") as f:
        f.write(client.audio.speech.create(**kw).content)
    cmd = ["ffmpeg", "-y", "-loglevel", "quiet", "-i", mp3]
    if rate:
        cmd += ["-ar", str(rate), "-ac", "1"]
    subprocess.run(cmd + [wav_path], check=True)
    os.unlink(mp3)


# --- recover bail texts from the existing wavs ---
bail_texts = {}
for name in BAIL_FILES:
    src = os.path.join(BAIL_DIR, name)
    bail_texts[name] = transcribe(src)  # NOTE: enroll_prompt garbles via whisper; correct text is "Enrolling your voice. After the beep, please speak naturally for about ten seconds."
    print(f"[text] {name}: {bail_texts[name]}")

# --- stage new clips ---
for d in (FILLER_DIR + ".new", BAIL_DIR + ".new"):
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)

for i, text in enumerate(FILLER_TEXTS, 1):
    synth_wav(text, f"{FILLER_DIR}.new/{i:02d}.wav")  # 24 kHz like the old pool
    print(f"  filler {i:02d} ok")

for name in BAIL_FILES:
    synth_wav(bail_texts[name], f"{BAIL_DIR}.new/{name}", rate=16000)  # old bail wavs are 16 kHz mono
    print(f"  bail {name} ok")

# --- swap in (old pools kept as .bak) ---
for live in (FILLER_DIR, BAIL_DIR):
    bak = f"{live}.bak-tts1-{STAMP}"
    shutil.rmtree(bak, ignore_errors=True)
    os.rename(live, bak)
    os.rename(live + ".new", live)
    print(f"[swap] {live}  (old -> {bak})")
print("done")
