from dotenv import load_dotenv
load_dotenv(os.path.join(APP, ".env"))
import voice_io
from voice_io import _sync_client, tts_create_kwargs, TTS_MODEL_DEFAULT, TTS_VOICE_DEFAULT, TTS_SPEED_DEFAULT

